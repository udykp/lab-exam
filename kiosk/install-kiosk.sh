#!/bin/bash
# =============================================================================
# SecureLab — Kiosk Session Installer
# -----------------------------------------------------------------------------
# Installs a DEDICATED login session that runs ONLY the SecureLab exam app.
# Because GNOME Shell is not running inside that session, there is no overview,
# no workspaces, no Alt+Tab target and no touchpad gestures — there is simply
# nothing to switch to. This is the real fix for "students switch away from the
# exam window": in-app shortcut blocking cannot win that fight on Wayland, so we
# move the lockdown down to the session/compositor layer where it is enforceable.
#
# Two sessions are installed, both selectable at the GDM login screen:
#   * "SecureLab Exam (Kiosk)"              -> cage (Wayland)  [PRIMARY]
#   * "SecureLab Exam (Kiosk X11 fallback)" -> openbox (X11)   [FALLBACK]
#
# Usage:
#   sudo bash kiosk/install-kiosk.sh [--autologin]
#
#   --autologin   also enable GDM autologin into the kiosk now. Recommended to
#                 leave OFF until you have verified the session works on the
#                 real lab hardware (then run: sudo /opt/securelab-kiosk/kiosk-exam-mode.sh).
# =============================================================================
set -euo pipefail

if [ "$(id -u)" -ne 0 ]; then
  echo "Please run as root:  sudo bash kiosk/install-kiosk.sh"
  exit 1
fi

# The kiosk session runs as the user who invoked sudo (they already have the
# repo, Node/NVM, the Python venv and the MySQL user set up).
KIOSK_USER="${SUDO_USER:-}"
if [ -z "$KIOSK_USER" ] || [ "$KIOSK_USER" = "root" ]; then
  echo "Could not determine the target kiosk user from \$SUDO_USER."
  echo "Re-run from the exam user's account, e.g.:  sudo bash kiosk/install-kiosk.sh"
  exit 1
fi

AUTOLOGIN=0
for arg in "$@"; do
  case "$arg" in
    --autologin) AUTOLOGIN=1 ;;
    *) echo "Unknown option: $arg"; exit 1 ;;
  esac
done

SCRIPT_DIR="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
DEST=/opt/securelab-kiosk

echo "==============================================="
echo "  SecureLab Kiosk Session Installer"
echo "==============================================="
echo "  Kiosk user : $KIOSK_USER"
echo "  Repo dir   : $REPO_DIR"
echo "  Install to : $DEST"
echo "  Autologin  : $([ "$AUTOLOGIN" -eq 1 ] && echo yes || echo no)"
echo "-----------------------------------------------"

# 1. Dependencies -------------------------------------------------------------
echo "[1/6] Installing cage (Wayland kiosk) + openbox (X11 fallback)..."
apt-get update -y || true
if ! apt-get install -y cage openbox; then
  echo "  WARNING: package install failed. Install manually: sudo apt-get install cage openbox"
fi

# 2. Stage launch scripts + helpers ------------------------------------------
echo "[2/6] Installing launch scripts to $DEST ..."
install -d -m 0755 "$DEST"
install -m 0755 "$SCRIPT_DIR/launch-cage.sh"      "$DEST/launch-cage.sh"
install -m 0755 "$SCRIPT_DIR/launch-x11.sh"       "$DEST/launch-x11.sh"
install -m 0644 "$SCRIPT_DIR/openbox-rc.xml"      "$DEST/openbox-rc.xml"
install -m 0755 "$SCRIPT_DIR/kiosk-exam-mode.sh"  "$DEST/kiosk-exam-mode.sh"
install -m 0755 "$SCRIPT_DIR/kiosk-admin-mode.sh" "$DEST/kiosk-admin-mode.sh"

# 3. Record environment for the launchers ------------------------------------
echo "[3/6] Writing $DEST/kiosk.env ..."
cat > "$DEST/kiosk.env" <<EOF
# Generated by install-kiosk.sh on $(date)
SECURELAB_APP_DIR="$REPO_DIR"
SECURELAB_KIOSK_USER="$KIOSK_USER"
EOF
chmod 0644 "$DEST/kiosk.env"

# 4. Install the GDM session entries -----------------------------------------
echo "[4/6] Installing GDM session entries..."
install -d -m 0755 /usr/share/wayland-sessions /usr/share/xsessions
install -m 0644 "$SCRIPT_DIR/securelab-kiosk-cage.desktop" /usr/share/wayland-sessions/securelab-kiosk-cage.desktop
install -m 0644 "$SCRIPT_DIR/securelab-kiosk-x11.desktop"  /usr/share/xsessions/securelab-kiosk-x11.desktop

# 5. Make the cage session this user's default -------------------------------
echo "[5/6] Setting '$KIOSK_USER' default session to the cage kiosk..."
ASVC="/var/lib/AccountsService/users/$KIOSK_USER"
install -d -m 0755 /var/lib/AccountsService/users
if [ -f "$ASVC" ]; then
  cp -a "$ASVC" "$ASVC.securelab.bak"
  sed -i '/^[[:space:]]*[Xx]\?[Ss]ession[[:space:]]*=/d' "$ASVC"
  grep -q '^\[User\]' "$ASVC" || printf '[User]\n' >> "$ASVC"
else
  printf '[User]\nSystemAccount=false\n' > "$ASVC"
fi
awk '
  /^\[User\]/ { print; print "Session=securelab-kiosk-cage"; print "XSession=securelab-kiosk-x11"; next }
  { print }
' "$ASVC" > "$ASVC.tmp" && mv "$ASVC.tmp" "$ASVC"
chmod 0600 "$ASVC"

# 6. Optional autologin -------------------------------------------------------
if [ "$AUTOLOGIN" -eq 1 ]; then
  echo "[6/6] Enabling GDM autologin for '$KIOSK_USER'..."
  "$DEST/kiosk-exam-mode.sh"
else
  echo "[6/6] Autologin NOT enabled (recommended until the session is verified)."
  echo "      Enable later with:  sudo $DEST/kiosk-exam-mode.sh"
fi

echo "-----------------------------------------------"
echo "Done. Apply with:  sudo systemctl restart gdm   (or reboot)"
echo
echo "At the login screen, '$KIOSK_USER' now defaults to 'SecureLab Exam (Kiosk)'."
echo "Use the gear icon to pick another session:"
echo "  * 'Ubuntu'                              -> normal admin desktop"
echo "  * 'SecureLab Exam (Kiosk X11 fallback)' -> X11 fallback if cage misbehaves"
echo
echo "Maintenance escape hatch:  sudo /opt/securelab-kiosk/kiosk-admin-mode.sh"
echo "==============================================="
